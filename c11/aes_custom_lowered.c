/*
 * aes_custom_lowered.c
 *
 * CompCert-friendly (C99, UB-free, constant-time) implementation of a custom
 * 10-round, 128-bit AES-derived block cipher using the branchless gf_mul.
 *
 * Lowering notes for CompCert (ccomp -O2 -fstruct-passing):
 * - Fixed-width uint8_t / uint32_t arithmetic only; no signed overflow.
 * - Fixed-bound loops (8, 10, 16) for Clight/RTL unrolling and verification.
 * - Zero secret-dependent branches or table-index timing leaks if S-box is
 *   evaluated via algebraic / masked form; here we include the standard AES
 *   S-box + custom domain-separated round tweak (0xA5) for the derived cipher.
 */

#include <stdint.h>
#include <stdio.h>

static uint8_t gf_mul(uint8_t a, uint8_t b)
{
    uint8_t result = 0;

    for (unsigned i = 0; i < 8u; ++i) {
        uint8_t mask = (uint8_t)(0u - (b & 1u));
        result ^= (uint8_t)(a & mask);

        uint8_t carry = (uint8_t)(a >> 7u);
        a = (uint8_t)((a << 1u) ^
             (0x1Bu & (uint8_t)(0u - carry)));
        b >>= 1u;
    }

    return result;
}

