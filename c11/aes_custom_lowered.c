static const uint8_t RCON[10] = {
    0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36
};

/* Custom AES-derived affine tweak byte applied per round key */
#define CUSTOM_TWEAK 0xA5u

static void add_round_key(uint8_t state[16], const uint8_t rk[16])
{
    for (unsigned i = 0; i < 16u; ++i) {
        state[i] ^= rk[i];
    }
}

static void sub_bytes(uint8_t state[16])
{
    for (unsigned i = 0; i < 16u; ++i) {
        state[i] = SBOX[state[i]];
    }
}

static void shift_rows(uint8_t s[16])
{
    uint8_t tmp[16];
    tmp[0]  = s[0];  tmp[1]  = s[5];  tmp[2]  = s[10]; tmp[3]  = s[15];
    tmp[4]  = s[4];  tmp[5]  = s[9];  tmp[6]  = s[14]; tmp[7]  = s[3];
    tmp[8]  = s[8];  tmp[9]  = s[13]; tmp[10] = s[2];  tmp[11] = s[7];
    tmp[12] = s[12]; tmp[13] = s[1];  tmp[14] = s[6];  tmp[15] = s[11];
    for (unsigned i = 0; i < 16u; ++i) {
        s[i] = tmp[i];
    }
}

static void mix_columns(uint8_t s[16])
{
    for (unsigned c = 0; c < 4u; ++c) {
        unsigned idx = c * 4u;
        uint8_t a0 = s[idx + 0u];
        uint8_t a1 = s[idx + 1u];
        uint8_t a2 = s[idx + 2u];
        uint8_t a3 = s[idx + 3u];

        s[idx + 0u] = (uint8_t)(gf_mul(0x02u, a0) ^ gf_mul(0x03u, a1) ^ a2 ^ a3);
        s[idx + 1u] = (uint8_t)(a0 ^ gf_mul(0x02u, a1) ^ gf_mul(0x03u, a2) ^ a3);
        s[idx + 2u] = (uint8_t)(a0 ^ a1 ^ gf_mul(0x02u, a2) ^ gf_mul(0x03u, a3));
        s[idx + 3u] = (uint8_t)(gf_mul(0x03u, a0) ^ a1 ^ a2 ^ gf_mul(0x02u, a3));
    }
}

static void key_expansion(const uint8_t key[16], uint8_t rk[11][16])
{
    for (unsigned i = 0; i < 16u; ++i) {
        rk[0][i] = key[i];
    }
    for (unsigned r = 1; r <= 10u; ++r) {
        const uint8_t *prev = rk[r - 1u];
        uint8_t *cur = rk[r];

        cur[0] = (uint8_t)(prev[0] ^ SBOX[prev[13]] ^ RCON[r - 1u] ^ CUSTOM_TWEAK);
        cur[1] = (uint8_t)(prev[1] ^ SBOX[prev[14]]);
        cur[2] = (uint8_t)(prev[2] ^ SBOX[prev[15]]);
        cur[3] = (uint8_t)(prev[3] ^ SBOX[prev[12]]);

        for (unsigned i = 4; i < 16u; ++i) {
            cur[i] = (uint8_t)(prev[i] ^ cur[i - 4u]);
        }
    }
}

void aes_custom_encrypt(const uint8_t pt[16], const uint8_t key[16], uint8_t ct[16])
{
    uint8_t rk[11][16];
    uint8_t state[16];

    key_expansion(key, rk);
    for (unsigned i = 0; i < 16u; ++i) {
        state[i] = pt[i];
    }

    add_round_key(state, rk[0]);

    for (unsigned r = 1; r <= 9u; ++r) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, rk[r]);
    }

    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, rk[10]);

    for (unsigned i = 0; i < 16u; ++i) {
        ct[i] = state[i];
    }
}

int main(void)
{
    uint8_t pt[16] = {
        0x32,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,
        0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x34
    };
    uint8_t key[16] = {
        0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,
        0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c
    };
    uint8_t ct[16];

    if (gf_mul(0x57u, 0x83u) != 0xC1u) {
        return 1;
    }

    aes_custom_encrypt(pt, key, ct);

    printf("gf_mul(0x57, 0x83) = 0x%02X\n", gf_mul(0x57u, 0x83u));
    printf("Ciphertext: ");
    for (unsigned i = 0; i < 16u; ++i) {
        printf("%02x", ct[i]);
    }
    printf("\n");
    return 0;
}
