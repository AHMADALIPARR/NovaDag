#!/usr/bin/env python3
"""
urom_gen.py — Assembler & Microcode ROM Generator for RIJNDAEL-uROM.
Reads bootloader.uasm + encryption.uasm, encodes 32-bit control words,
and emits:
  1. microcode/encryption.mem   (4096 x 32-bit hex ROM image)
  2. vhdl/rijndael_urom.vhd     (synthesizable VHDL-2008 uROM with WCS option)
"""

from pathlib import Path
import re

OPCODES = {
    "NOP": 0x0, "LOAD": 0x1, "STORE": 0x2, "XOR": 0x3,
    "GF_MUL": 0x4, "SUBBYTE": 0x5, "SHIFTROW": 0x6, "MIXCOLUMN": 0x7,
    "KEYSTEP": 0x8, "BRANCH": 0x9, "LOOP": 0xA, "HALT": 0xF,
}

REGS = {
    "STATE": 0x00, "RKEY": 0x01, "BOOT_REG": 0x02, "CRC_REG": 0x03,
    "LC0": 0x04, "LC1": 0x05, "STATUS": 0x06,
    "EXT_PT": 0x10, "EXT_KEY": 0x11, "EXT_CT": 0x12,
    "BOOT_BUS": 0x13, "RCON": 0x14,
}


def parse_val(tok: str, labels: dict[str, int]) -> int:
    tok = tok.strip()
    if tok in labels:
        return labels[tok]
    if tok in REGS:
        return REGS[tok]
    return int(tok, 0)


def assemble(files: list[Path]) -> tuple[list[int], dict[int, str]]:
    rom = [0xF0000000] * 4096  # Default HALT
    comments: dict[int, str] = {}
    labels: dict[str, int] = {}
    parsed: list[tuple[int, str, list[str], str]] = []

    # Pass 1: collect labels & instructions
    for fpath in files:
        pc = 0
        for raw in fpath.read_text().splitlines():
            line = raw.split(";", 1)[0].strip()
            if not line:
                continue
            if line.startswith(".org"):
                pc = int(line.split()[1], 0)
                continue
            if line.endswith(":"):
                labels[line[:-1].strip()] = pc
                continue
            parts = re.split(r"[\s,]+", line)
            op = parts[0].upper()
            args = [p for p in parts[1:] if p]
            parsed.append((pc, op, args, line))
            pc += 1

    # Pass 2: encode 32-bit words
    for pc, op, args, src_line in parsed:
        opcode = OPCODES[op]
        dest = parse_val(args[0], labels) if len(args) > 0 else 0
        src = parse_val(args[1], labels) if len(args) > 1 else 0
        ctrl = parse_val(args[2], labels) if len(args) > 2 else 0
        imm12 = parse_val(args[3], labels) if len(args) > 3 else 0
        word = (
            ((opcode & 0xF) << 28)
            | ((dest & 0x3F) << 22)
            | ((src & 0x3F) << 16)
            | ((ctrl & 0xF) << 12)
            | (imm12 & 0xFFF)
        )
        rom[pc] = word
        comments[pc] = src_line

    return rom, comments


def emit_mem(rom: list[int], out_path: Path) -> None:
    out_path.write_text("\n".join(f"{w:08X}" for w in rom) + "\n")


def emit_vhdl(rom: list[int], comments: dict[int, str], out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "-- Auto-generated by urom_gen.py (RIJNDAEL-uROM 4096 x 32-bit)",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "",
        "entity rijndael_urom is",
        "  port (",
        "    clk     : in  std_logic;",
        "    we      : in  std_logic; -- Writable Control Store (WCS) bootloader patch port",
        "    waddr   : in  unsigned(11 downto 0);",
        "    wdata   : in  std_logic_vector(31 downto 0);",
        "    address : in  unsigned(11 downto 0);",
        "    data    : out std_logic_vector(31 downto 0)",
        "  );",
        "end entity rijndael_urom;",
        "",
        "architecture rtl of rijndael_urom is",
        "  type rom_t is array (0 to 4095) of std_logic_vector(31 downto 0);",
        "  signal rom_mem : rom_t := (",
    ]
    for addr in sorted(comments.keys()):
        lines.append(f'    {addr:4d} => x"{rom[addr]:08X}", -- {comments[addr]}')
    lines.extend([
        '    others => x"F0000000"',
        "  );",
        "begin",
        "  process(clk)",
        "  begin",
        "    if rising_edge(clk) then",
        "      if we = '1' then",
        "        rom_mem(to_integer(waddr)) <= wdata;",
        "      end if;",
        "    end if;",
        "  end process;",
        "",
        "  data <= rom_mem(to_integer(address));",
        "end architecture rtl;",
        "",
    ])
    out_path.write_text("\n".join(lines))


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    rom, comments = assemble([
        root / "microcode" / "bootloader.uasm",
        root / "microcode" / "encryption.uasm",
    ])
    emit_mem(rom, root / "microcode" / "encryption.mem")
    emit_vhdl(rom, comments, root / "vhdl" / "rijndael_urom.vhd")
    print(f"Assembled {len(comments)} microinstructions into encryption.mem and rijndael_urom.vhd")
    for addr in sorted(comments.keys()):
        print(f"  0x{addr:03X}: {rom[addr]:08X}  ; {comments[addr]}")


if __name__ == "__main__":
    main()
